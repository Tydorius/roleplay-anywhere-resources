def _insert_line(room, axis, line):
    """A copy of the room with one empty line inserted at ``line``: pieces on
    the far side (and doors, stretch lines and the filler) shift past it."""
    r = copy.deepcopy(room)
    w, h = r["size"]
    if axis == "x":
        r["size"] = [w + 1, h]
        for p in r.get("pieces") or []:
            if p.get("at") and p["at"][0] >= line:
                p["at"][0] += 1
        d = r.setdefault("doors", {})
        for side in ("north", "south"):
            if isinstance(d.get(side), list):
                d[side] = [k + 1 if k >= line else k for k in d[side]]
        st = r.setdefault("stretch", {})
        if isinstance(st.get("x"), list):
            st["x"] = [v + 1 if v >= line else v for v in st["x"]]
        if isinstance(r.get("filler"), dict) and r["filler"].get("at"):
            fx, fw = r["filler"]["at"][0], r["filler"]["size"][0]
            if fx >= line:
                r["filler"]["at"][0] += 1
            elif fx + fw > line:
                r["filler"]["size"][0] += 1
    else:
        r["size"] = [w, h + 1]
        for p in r.get("pieces") or []:
            if p.get("at") and p["at"][1] >= line:
                p["at"][1] += 1
        d = r.setdefault("doors", {})
        for side in ("west", "east"):
            if isinstance(d.get(side), list):
                d[side] = [k + 1 if k >= line else k for k in d[side]]
        st = r.setdefault("stretch", {})
        if isinstance(st.get("y"), list):
            st["y"] = [v + 1 if v >= line else v for v in st["y"]]
        if isinstance(r.get("filler"), dict) and r["filler"].get("at"):
            fy, fh = r["filler"]["at"][1], r["filler"]["size"][1]
            if fy >= line:
                r["filler"]["at"][1] += 1
            elif fy + fh > line:
                r["filler"]["size"][1] += 1
    return r


def _line_covered(room, axis, line):
    for p in room.get("pieces") or []:
        if not isinstance(p, dict):
            continue
        at, size = p.get("at"), p.get("size")
        if not (isinstance(at, list) and len(at) == 2
                and isinstance(size, list) and len(size) == 2):
            continue
        i = 0 if axis == "x" else 1
        if at[i] <= line < at[i] + size[i]:
            return True
    return False


def stretch_ok(room, axis, line, groups=None, lib=None):
    """An error string when an empty line inserted at ``line`` (an x column
    or y row) breaks the room, None when the turned-out room still passes
    every check (the size band is skipped: growth is the point of the
    line)."""
    size = room.get("size") or [0, 0]
    top = size[0] if axis == "x" else size[1]
    if not isinstance(line, int) or isinstance(line, bool) \
            or not 0 <= line <= top:
        return (f"stretch {axis} {line!r} is not a position in 0..{top}")
    turned = _insert_line(room, axis, line)
    if _line_covered(turned, axis, line):
        return f"stretch {axis} {line} runs through a piece"
    turned["stretch"] = {"x": [], "y": []}
    errors = []
    _check_room(turned, groups, lib, errors.append, check_band=False)
    if errors:
        return f"inserting at {axis} {line} breaks the room ({errors[0]})"
    return None
