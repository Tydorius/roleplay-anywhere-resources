"""Fixed rooms: the library's stored rooms, every piece placed by role and
its door cells known — generated by the composer (worldgen/room_composer.py,
design section 5) and checked here (design section 6). One JSON file per
family under ``library/rooms/`` holding a ``rooms`` list; a missing folder
means no rooms have been generated yet.

  load(path=None)                      -> [room, ...], each carrying "_file"
  check(rooms, groups=None, lib=None)  -> [error, ...], plain sentences
  use_sides(piece, siblings)           -> the sides a piece is used from
  dead_cells(room)                     -> the free cells too far from every
                                         piece to be walked on
  instances(room)                      -> the placed group instances as boxes
  rotate(room, quarter_turns, mirror=False) -> the turned room
  stretch_ok(room, axis, line, groups=None, lib=None) -> an error string, or
                                          None when an empty line inserted
                                          there keeps the room valid
"""
import copy
import json
import os
from collections import Counter

from .library import ID_RE, LIB_DIR, SIDES

ROOMS_DIR = os.path.join(LIB_DIR, "rooms")
CLEARANCES = ("tight", "roomy", "grand")
CLEARANCE_GAP = {"tight": 1, "roomy": 2, "grand": 3}
STYLES = ("flush", "open")
# library.json's sizeBands, measured on the whole room now (there is no wall
# ring to subtract). The composer labels rooms from this table without loading
# the library; check() always prefers the library's own bands.
BANDS = {"tiny": (1, 11), "small": (12, 24), "medium": (25, 48), "large": (49, 400)}
SLEEP_SINGLE_ROLES = ("sleep", "sleep.child", "med.bed", "cell.bed")
SLEEP_COUPLE_ROLE = "sleep.couple"
SEAT_ROLES = ("seat", "seat.long", "seat.lounge", "seat.state")
# what a seat is placed at, inside the same group: it is used from the side
# facing away from these
BELONG_ROLES = ("desk", "counter.serve", "counter.prep")
FREE_TABLE_ROLES = ("desk",)      # plus every role starting "table."
OPPOSITE = {"north": "south", "south": "north", "east": "west", "west": "east"}
TURN = {"north": "east", "east": "south", "south": "west", "west": "north"}
FLIP_EW = {"east": "west", "west": "east"}
FLIP_NS = {"north": "south", "south": "north"}
MAX_SIDE = 40


def load(path=None):
    """Every ``library/rooms/<family>.json`` as a flat list of room dicts,
    sorted by file name, each carrying its file in ``_file``. A missing
    folder is an empty list (no rooms have been generated yet); a file that
    isn't valid JSON becomes a "!<file>" room carrying ``_load_error``, so
    ``check`` reports it instead of losing it."""
    folder = path or ROOMS_DIR
    rooms = []
    if not os.path.isdir(folder):
        return rooms
    for p in sorted(os.path.join(folder, n) for n in os.listdir(folder)
                    if n.endswith(".json")):
        name = os.path.basename(p)
        try:
            with open(p, "r", encoding="utf-8") as fh:
                raw = json.load(fh)
        except (OSError, ValueError) as e:
            rooms.append({"id": "!" + name, "_file": name, "_load_error": str(e)})
            continue
        if not isinstance(raw, dict):
            rooms.append({"id": "!" + name, "_file": name,
                          "_load_error": "not a JSON object"})
            continue
        for r in raw.get("rooms") or []:
            if isinstance(r, dict):
                r = dict(r)
                r["_file"] = name
                rooms.append(r)
    return rooms


def band_for_area(area, bands=None):
    """The size band name a room of this many cells falls into, or None when
    it fits no band."""
    for name, rng in sorted((n, tuple(r)) for n, r in (bands or BANDS).items()
                            if isinstance(r, (list, tuple)) and len(r) == 2):
        if rng[0] <= area <= rng[1]:
            return name
    return None


# ------------------------------------------------------------- the use table

def use_sides(piece, siblings=()):
    """The sides people stand or sit at to use one piece — the table the
    reachability check runs on: a piece needs a free, reached cell on one of
    these sides. ``siblings`` are the room's pieces of the same group, the
    seat's table among them.

      beds (sleep, sleep.couple, sleep.child,   a long side (all of them
      med.bed, cell.bed)                         when the bed is square)
      seats (seat, seat.long, seat.lounge,      the side facing away from
      seat.state)                                the table, desk or counter
                                                in the same group (unless
                                                its own group's pieces
                                                cover that side — a seat
                                                wedged beside the table —
                                                then like a lone seat); a
                                                lone seat's front when it
                                                backs a wall, else any side
      a piece with a back                       its front
      free-standing tables and desks            any side
      lights, decor, optional pieces            none
      anything else (chest, coat rack, basin)   any side
    """
    role = piece.get("role") or ""
    if piece.get("optional"):
        return ()
    if role.startswith("light") or role.startswith("decor"):
        return ()
    if role in SLEEP_SINGLE_ROLES or role == SLEEP_COUPLE_ROLE:
        w, h = piece.get("size") or (1, 1)
        long = tuple(s for s in SIDES
                     if (s in ("north", "south") and w >= 2)
                     or (s in ("east", "west") and h >= 2))
        return long or SIDES
    if role in SEAT_ROLES:
        away = _away_side(piece, siblings)
        if away and not _side_covered(piece, away, siblings):
            return (away,)
        back = piece.get("back")
        return (OPPOSITE[back],) if back in OPPOSITE else SIDES
    back = piece.get("back")
    if back in OPPOSITE:
        return (OPPOSITE[back],)
    if role.startswith("table.") or role in FREE_TABLE_ROLES:
        return SIDES
    return SIDES


def _away_side(piece, siblings):
    """The side of a seat facing away from the table-like piece it belongs
    to, or None when its group has none."""
    x, y = piece.get("at") or (0, 0)
    w, h = piece.get("size") or (1, 1)
    best = None
    best_d = None
    for o in siblings:
        if o is piece:
            continue
        role = o.get("role") or ""
        if not (role.startswith("table.") or role in BELONG_ROLES):
            continue
        ox, oy = o.get("at") or (0, 0)
        ow, oh = o.get("size") or (1, 1)
        dx = ox + ow / 2 - (x + w / 2)
        dy = oy + oh / 2 - (y + h / 2)
        d = abs(dx) + abs(dy)
        if best_d is None or d < best_d:
            best_d = d
            if abs(dx) >= abs(dy):
                best = "west" if dx > 0 else "east"
            else:
                best = "north" if dy > 0 else "south"
    return best


def _side_covered(piece, side, siblings):
    """Whether every cell on one side of a piece is covered by another piece
    of its own group — a seat wedged between its table and another piece."""
    x, y = piece.get("at") or (0, 0)
    w, h = piece.get("size") or (1, 1)
    if side == "north":
        cells = [(cx, y - 1) for cx in range(x, x + w)]
    elif side == "south":
        cells = [(cx, y + h) for cx in range(x, x + w)]
    elif side == "west":
        cells = [(x - 1, cy) for cy in range(y, y + h)]
    else:
        cells = [(x + w, cy) for cy in range(y, y + h)]
    for o in siblings:
        if o is piece:
            continue
        ox, oy = o.get("at") or (0, 0)
        ow, oh = o.get("size") or (1, 1)
        cells = [c for c in cells
                 if not (ox <= c[0] < ox + ow and oy <= c[1] < oy + oh)]
        if not cells:
            return True
    return not cells


# ----------------------------------------------------------------- instances

def _touch(a, b):
    """Two piece rects share an edge (not just a corner)."""
    ax, ay, aw, ah = a
    bx, by, bw, bh = b
    gx = max(bx - (ax + aw), ax - (bx + bw))
    gy = max(by - (ay + ah), ay - (by + bh))
    return (gx <= 0 and gy == 0) or (gy <= 0 and gx == 0)


def _rect(p):
    at, size = p.get("at"), p.get("size")
    return None if not (isinstance(at, list) and len(at) == 2
                        and isinstance(size, list) and len(size) == 2) \
        else (at[0], at[1], size[0], size[1])


def instances(room):
    """The placed group instances: pieces of one group id that touch edge to
    edge are one instance (copies of a repeatable group always sit a
    clearance apart, so they never touch). Each entry is
    {"gid", "box": (x, y, w, h), "indices": [piece indexes], "back": side}."""
    pieces = room.get("pieces") or []
    out = []
    used = [False] * len(pieces)
    for i, p in enumerate(pieces):
        if used[i] or not isinstance(p, dict) or _rect(p) is None:
            continue
        gid = p.get("group")
        used[i] = True
        cluster = [i]
        grew = True
        while grew:
            grew = False
            for j, q in enumerate(pieces):
                if used[j] or not isinstance(q, dict) or q.get("group") != gid \
                        or _rect(q) is None:
                    continue
                if any(_touch(_rect(pieces[k]), _rect(q)) for k in cluster):
                    used[j] = True
                    cluster.append(j)
                    grew = True
        rects = [_rect(pieces[k]) for k in cluster]
        xs = [r[0] for r in rects]
        ys = [r[1] for r in rects]
        box = (min(xs), min(ys),
               max(r[0] + r[2] for r in rects) - min(xs),
               max(r[1] + r[3] for r in rects) - min(ys))
        back = next((pieces[k].get("back") for k in cluster
                     if pieces[k].get("back") in SIDES), None)
        out.append({"gid": gid, "box": box, "indices": cluster, "back": back})
    return out


# ------------------------------------------------------------------- turning

def rotate(room, quarter_turns, mirror=False):
    """The room turned: ``quarter_turns`` quarter turns clockwise, and
    mirrored across the vertical axis first when ``mirror`` is set — sizes,
    ``at``, ``back``, door sides and offsets, stretch lines and the filler
    area all turn with the furniture. Four turns (and no mirror) return the
    room unchanged; every result passes ``check`` unchanged."""
    r = copy.deepcopy({k: v for k, v in room.items() if not k.startswith("_")})
    if mirror:
        r = _mirror_room(r)
    for _ in range(int(quarter_turns) % 4):
        r = _turn_room(r)
    return r


def _turn_room(r):
    w, h = r["size"]
    n = dict(r)
    n["size"] = [h, w]
    n["pieces"] = []
    for p in r.get("pieces") or []:
        q = dict(p)
        x, y = q.get("at") or [0, 0]
        pw, ph = q.get("size") or [0, 0]
        q["at"] = [h - y - ph, x]
        q["size"] = [ph, pw]
        if q.get("back") in TURN:
            q["back"] = TURN[q["back"]]
        n["pieces"].append(q)
    d = r.get("doors") or {}
    nd = {}
    for k in d.get("north") or []:
        nd.setdefault("east", []).append(k)
    for k in d.get("east") or []:
        nd.setdefault("south", []).append(h - 1 - k)
    for k in d.get("south") or []:
        nd.setdefault("west", []).append(k)
    for k in d.get("west") or []:
        nd.setdefault("north", []).append(h - 1 - k)
    n["doors"] = {s: sorted(v) for s, v in nd.items() if v}
    st = r.get("stretch") or {}
    n["stretch"] = {axis: lines for axis, lines in
                    (("x", sorted(h - v for v in st.get("y") or [])),
                     ("y", sorted(st.get("x") or []))) if lines}
    if isinstance(r.get("filler"), dict):
        f = r["filler"]
        fx, fy = f.get("at") or [0, 0]
        fw, fh = f.get("size") or [0, 0]
        n["filler"] = {"at": [h - fy - fh, fx], "size": [fh, fw]}
    return n


def _mirror_room(r):
    w = r["size"][0]
    n = dict(r)
    n["pieces"] = []
    for p in r.get("pieces") or []:
        q = dict(p)
        x, y = q.get("at") or [0, 0]
        pw, ph = q.get("size") or [0, 0]
        q["at"] = [w - x - pw, y]
        if q.get("back") in FLIP_EW:
            q["back"] = FLIP_EW[q["back"]]
        n["pieces"].append(q)
    d = r.get("doors") or {}
    nd = {}
    for s in ("north", "south"):
        if s in d:
            nd[s] = sorted(w - 1 - k for k in d.get(s) or [])
    if "west" in d:
        nd["east"] = sorted(d.get("west") or [])
    if "east" in d:
        nd["west"] = sorted(d.get("east") or [])
    n["doors"] = {s: v for s, v in nd.items() if v}
    st = r.get("stretch") or {}
    n["stretch"] = {axis: lines for axis, lines in
                    (("x", sorted(w - v for v in st.get("x") or [])),
                     ("y", sorted(st.get("y") or []))) if lines}
    if isinstance(r.get("filler"), dict):
        f = r["filler"]
        fx, fy = f.get("at") or [0, 0]
        fw, fh = f.get("size") or [0, 0]
        n["filler"] = {"at": [w - fx - fw, fy], "size": [fw, fh]}
    return n


# -------------------------------------------------------------------- checks

def _bands(lib):
    if not lib:
        return BANDS
    bands = {n: tuple(r) for n, r in (lib.vocab.get("sizeBands") or {}).items()
             if isinstance(r, list) and len(r) == 2}
    return bands or BANDS


def _int_pair(v, lo=0, hi=MAX_SIDE):
    return (isinstance(v, list) and len(v) == 2
            and all(isinstance(x, int) and not isinstance(x, bool)
                    and lo <= x <= hi for x in v))


def _cells(rect):
    x, y, w, h = rect
    return [(cx, cy) for cx in range(x, x + w) for cy in range(y, y + h)]


def _side_cells(x, y, w, h, sides, W, H):
    out = []
    for s in sides:
        if s == "north":
            out += [(cx, y - 1) for cx in range(x, x + w)]
        elif s == "south":
            out += [(cx, y + h) for cx in range(x, x + w)]
        elif s == "west":
            out += [(x - 1, cy) for cy in range(y, y + h)]
        else:
            out += [(x + w, cy) for cy in range(y, y + h)]
    return [c for c in out if 0 <= c[0] < W and 0 <= c[1] < H]


def _aspect_cap(family):
    """The family's cap on long side over short side, from the composer's
    constant (imported, never copied; the import stays lazy because the
    composer imports this module)."""
    from . import room_composer
    return room_composer.aspect_cap(family)


def dead_cells(room):
    """The room's dead floor: free cells more than the clearance's gap + 1
    cells (Chebyshev) from every piece — floor nobody walks on between
    furniture. In an open room the filler and the ring of cells around it
    are walking floor too (the middle people cross), never dead. A room
    whose size is broken reports no cells; its error is elsewhere."""
    size = room.get("size")
    if not _int_pair(size, 1):
        return []
    w, h = size
    gap = CLEARANCE_GAP.get(room.get("clearance"), 1)
    rects = [r for r in (_rect(p) for p in room.get("pieces") or []) if r]
    filler = room.get("filler") if room.get("style") == "open" else None
    if not (isinstance(filler, dict) and _int_pair(filler.get("at"))
            and _int_pair(filler.get("size"), 1)):
        filler = None
    out = []
    for x in range(w):
        for y in range(h):
            if any(_chebyshev(x, y, r) <= gap + 1 for r in rects):
                continue
            if filler is not None and _chebyshev(x, y, (filler["at"][0],
                                                        filler["at"][1],
                                                        filler["size"][0],
                                                        filler["size"][1])) <= 1:
                continue
            out.append((x, y))
    return out


def _chebyshev(x, y, rect):
    """The Chebyshev distance from a cell to a rectangle (0 inside it)."""
    rx, ry, rw, rh = rect
    return max(rx - x, 0, x - (rx + rw - 1), ry - y, 0, y - (ry + rh - 1))


def _check_room(room, groups, lib, err, check_band=True):
    """Every rule that holds per room, as plain sentences through ``err``.
    ``check_band`` is off while validating a stretch line, where the inserted
    line deliberately grows the room."""
    if not isinstance(room, dict):
        err("a room must be a JSON object")
        return
    rid = room.get("id")
    if not isinstance(rid, str) or not ID_RE.match(rid):
        err("id must be lower case words separated by dots")
    fam = room.get("family")
    if lib and fam not in (lib.vocab.get("families") or {}):
        err(f"unknown family {fam!r}")
    if room.get("clearance") not in CLEARANCES:
        err(f"clearance must be one of {'/'.join(CLEARANCES)}")
    if room.get("style") not in STYLES:
        err(f"style must be one of {'/'.join(STYLES)}")
    wealth = room.get("wealth")
    if not isinstance(wealth, list) or not wealth:
        err("wealth must list tiers")
    elif lib and any(t not in lib.tiers for t in wealth):
        err(f"wealth must list {lib.tiers}")
    size = room.get("size")
    if not _int_pair(size, 1):
        err("size must be [w, h], 1-40 cells")
        return
    w, h = size
    cap = _aspect_cap(room.get("family"))
    if max(w, h) > cap * min(w, h):
        err(f"aspect {w}x{h} is over the family cap {cap:g}: the long side "
            f"may be at most {cap:g}x the short side")
    for key in ("outdoor", "symmetric"):
        if not isinstance(room.get(key), bool):
            err(f"{key} must be true or false")
    if not isinstance(room.get("recipe"), str) or not room["recipe"]:
        err("recipe must name the source recipe")
    if not isinstance(room.get("description"), str) or not room["description"].strip():
        err("description must be a sentence")
    sleeps = room.get("sleeps")
    if not isinstance(sleeps, dict) \
            or set(sleeps) - {"singles", "couples"} \
            or any(not isinstance(sleeps.get(k), int)
                   or isinstance(sleeps.get(k), bool) or sleeps.get(k) < 0
                   for k in ("singles", "couples")):
        err('sleeps must be {"singles": n, "couples": n}')
        sleeps = None
    pieces = room.get("pieces")
    if not isinstance(pieces, list) or not pieces:
        err("pieces must be a list with at least one piece")
        return
    roles = (lib.vocab.get("roles") or {}) if lib else {}
    gids = ((groups or {}).get("groups") or {})
    rects = []
    for p in pieces:
        if not isinstance(p, dict) or not _int_pair(p.get("size"), 1, 12) \
                or not _int_pair(p.get("at")):
            err("every piece must be an object with size [w, h] and at [x, y]")
            rects.append(None)
            continue
        role = p.get("role")
        if lib and role not in roles:
            err(f"unknown role {role!r}")
        if groups is not None and p.get("group") not in gids:
            err(f"names no group {p.get('group')!r}")
        if p.get("back") is not None and p.get("back") not in SIDES:
            err(f"piece {role!r} back must be one of {'/'.join(SIDES)} or left out")
        if p.get("optional") is not None and not isinstance(p.get("optional"), bool):
            err(f"piece {role!r} optional must be true or false")
        at, sz = p["at"], p["size"]
        rects.append((at[0], at[1], sz[0], sz[1]))
    ok = [i for i, r in enumerate(rects) if r]
    for i in ok:
        x, y, pw, ph = rects[i]
        if x < 0 or y < 0 or x + pw > w or y + ph > h:
            err(f"piece {pieces[i].get('role')!r} at {pieces[i]['at']} "
                f"stands outside the room")
    for a in range(len(ok)):
        for b in range(a + 1, len(ok)):
            i, j = ok[a], ok[b]
            xi, yi, wi, hi = rects[i]
            xj, yj, wj, hj = rects[j]
            if xi < xj + wj and xj < xi + wi and yi < yj + hj and yj < yi + hi:
                err(f"pieces {pieces[i].get('role')!r} and "
                    f"{pieces[j].get('role')!r} overlap")
    # wall-bound pieces: flush against the wall they back
    for i in ok:
        back = pieces[i].get("back")
        if back not in SIDES:
            continue
        x, y, pw, ph = rects[i]
        on = {"north": y == 0, "south": y + ph == h,
              "west": x == 0, "east": x + pw == w}[back]
        if not on:
            err(f"piece {pieces[i].get('role')!r} backs {back} off the room's "
                f"{back} edge")
    # doors: free edge cells that can take one, on at least two sides
    doors = room.get("doors")
    if not isinstance(doors, dict):
        doors = {}
        err("doors must list sides")
    occupied = {c for i in ok for c in _cells(rects[i])}
    door_cells = []
    sides_with = 0
    for side in SIDES:
        offs = doors.get(side)
        if offs is None:
            continue
        if not isinstance(offs, list):
            err(f"doors.{side} must be a list of cell offsets")
            continue
        if offs:
            sides_with += 1
        seen = set()
        for k in offs:
            if not isinstance(k, int) or isinstance(k, bool) or k < 0 \
                    or k >= (w if side in ("north", "south") else h):
                err(f"door cell {side} {k!r} is not on that wall")
            elif k in seen:
                err(f"door cell {side} {k} repeats")
            else:
                seen.add(k)
                cell = {"north": (k, 0), "south": (k, h - 1),
                        "west": (0, k), "east": (w - 1, k)}[side]
                if cell in occupied:
                    err(f"door cell {side} {k} is blocked by a piece")
                else:
                    door_cells.append(cell)
    if sides_with < 2:
        err(f"door cells on {sides_with} side(s); at least two sides need one")
    # reachability: one free area, reached from every door cell
    free = {(x, y) for x in range(w) for y in range(h)} - occupied
    reach = set()
    if door_cells:
        start = door_cells[0]
        if start in free:
            reach = {start}
            stack = [start]
            while stack:
                cx, cy = stack.pop()
                for nb in ((cx + 1, cy), (cx - 1, cy),
                           (cx, cy + 1), (cx, cy - 1)):
                    if nb in free and nb not in reach:
                        reach.add(nb)
                        stack.append(nb)
        if free - reach:
            err(f"{len(free - reach)} free cell(s) cannot be reached "
                f"from the doors")
        for cell in door_cells:
            if cell not in reach:
                err(f"door cell {cell[0]},{cell[1]} is cut off from the "
                    f"other doors")
    # dead floor: a free cell more than gap + 1 from every piece is floor
    # nobody walks on (an open room's filler and its ring are walked)
    dead = dead_cells(room)
    if dead:
        gap = CLEARANCE_GAP.get(room.get("clearance"), 1)
        err(f"{len(dead)} dead floor cell(s) (first at {dead[0][0]},"
            f"{dead[0][1]}): more than {gap + 1} cells from every piece at "
            f"{room.get('clearance')} clearance")
    # use sides: a reached cell next to every piece it can be used from
    by_group = {}
    for i in ok:
        by_group.setdefault(pieces[i].get("group"), []).append(pieces[i])
    for i in ok:
        p = pieces[i]
        sides = use_sides(p, by_group.get(p.get("group")) or [])
        if not sides:
            continue
        x, y, pw, ph = rects[i]
        if not any(c in reach for c
                   in _side_cells(x, y, pw, ph, sides, w, h)):
            err(f"piece {p.get('role')!r} at {p['at']} has no reached cell "
                f"on its use sides {'/'.join(sides)}")
    # sleep counts match the pieces
    if sleeps is not None:
        ns = sum(1 for i in ok if pieces[i].get("role") in SLEEP_SINGLE_ROLES)
        nc = sum(1 for i in ok if pieces[i].get("role") == SLEEP_COUPLE_ROLE)
        if (ns, nc) != (sleeps.get("singles", 0), sleeps.get("couples", 0)):
            err(f"sleeps {dict((k, sleeps.get(k, 0)) for k in ('singles', 'couples'))} "
                f"does not match the pieces ({ns} singles, {nc} couples)")
    # size band fits the whole room's area
    if check_band:
        bands = _bands(lib)
        rng = bands.get(room.get("sizeBand"))
        if rng is None:
            err(f"unknown sizeBand {room.get('sizeBand')!r}")
        elif not rng[0] <= w * h <= rng[1]:
            err(f"area {w * h} is outside size band {room.get('sizeBand')} "
                f"({rng[0]}-{rng[1]})")
    # a symmetric room mirrors across one centre line
    if room.get("symmetric") and not _mirror_symmetric(pieces, rects, ok, w, h):
        err("flagged symmetric but its pieces do not mirror across either "
            "centre line")
    # the filler area of an open room: a clear rectangle of at least 2x2,
    # inside the room and off every wall, its cells reached from the doors
    filler = room.get("filler")
    if room.get("style") == "open":
        if not isinstance(filler, dict) or not _int_pair(filler.get("at")) \
                or not _int_pair(filler.get("size"), 1) \
                or filler["size"][0] < 2 or filler["size"][1] < 2:
            err("an open room needs a filler area of at least 2x2")
            filler = None
    fx = fy = fw = fh = 0
    if isinstance(filler, dict) and _int_pair(filler.get("at")) \
            and _int_pair(filler.get("size"), 1):
        fx, fy = filler["at"]
        fw, fh = filler["size"]
        bad = (fx < 0 or fy < 0 or fx + fw > w or fy + fh > h
               or any(c in occupied for c in _cells((fx, fy, fw, fh))))
        if bad:
            err(f"filler at {filler['at']} is not a clear area inside the room")
            filler = None
    if filler is not None and (fx <= 0 or fy <= 0 or fx + fw >= w
                               or fy + fh >= h):
        err(f"filler at {filler['at']} touches the room edge; the open "
            f"middle keeps a clear cell to every wall")
        filler = None
    if filler is not None and any(c not in reach
                                  for c in _cells((fx, fy, fw, fh))):
        err("the filler area cannot be reached from the doors")
    # empty edge lines: a full row or column along a wall with no piece and
    # no filler cell on it. A flush room allows at most the one slack line
    # per wall; an open room only the line its middle needs — the buffer
    # line the filler keeps to that wall
    fcells = set(_cells((fx, fy, fw, fh))) if filler is not None else set()
    for side, k in _edge_line_counts(w, h, occupied, fcells).items():
        if k < 1:
            continue
        if room.get("style") == "open":
            needed = filler is not None and {
                "north": fy == 1, "south": fy + fh == h - 1,
                "west": fx == 1, "east": fx + fw == w - 1}[side]
            if not needed:
                err(f"{k} empty line(s) along the {side} wall; an open room "
                    f"keeps only the line its open middle needs")
        elif k > 1:
            err(f"{k} empty lines along the {side} wall; a flush room "
                f"allows at most one slack line")
    # stretch lines stay insertable
    st = room.get("stretch")
    if not isinstance(st, dict):
        st = {}
        err("stretch must hold x and y line lists")
    for axis, top in (("x", w), ("y", h)):
        lines = st.get(axis)
        if lines is None:
            continue
        if not isinstance(lines, list):
            err(f"stretch.{axis} must be a list of lines")
            continue
        for line in lines:
            e = stretch_ok(room, axis, line, groups, lib)
            if e:
                err(e)


def _edge_line_counts(w, h, occupied, filler):
    """How many full lines sit empty along each wall: the consecutive rows
    from the north (or the columns from the west, and so on) with no piece
    and no filler cell on them."""
    def row_empty(y):
        return not any((x, y) in occupied or (x, y) in filler
                       for x in range(w))

    def col_empty(x):
        return not any((x, y) in occupied or (x, y) in filler
                       for y in range(h))

    counts = {}
    for side, lines in (("north", range(h)), ("south", range(h - 1, -1, -1)),
                        ("west", range(w)), ("east", range(w - 1, -1, -1))):
        empty = row_empty if side in ("north", "south") else col_empty
        k = 0
        for i in lines:
            if not empty(i):
                break
            k += 1
        counts[side] = k
    return counts


def _mirror_symmetric(pieces, rects, ok, w, h):
    """The pieces mirror across the vertical or the horizontal centre line:
    every piece has a partner at the mirrored cell with the same role, size
    and mirrored back."""
    for axis, span in (("x", w), ("y", h)):
        a, b = Counter(), Counter()
        for i in ok:
            p = pieces[i]
            x, y, pw, ph = rects[i]
            key = (p.get("role"), (pw, ph), p.get("back"), x, y)
            if axis == "x":
                mkey = (p.get("role"), (pw, ph),
                        FLIP_EW.get(p.get("back"), p.get("back")),
                        span - x - pw, y)
            else:
                mkey = (p.get("role"), (pw, ph),
                        FLIP_NS.get(p.get("back"), p.get("back")),
                        x, span - y - ph)
            a[key] += 1
            b[mkey] += 1
        if a == b:
            return True
    return False


def check(rooms, groups=None, lib=None):
    """Every rule of the fixed-room format the code can check, as plain
    sentences starting with the file and room: pieces inside the room and not
    overlapping, wall-bound pieces flush against their wall, door cells valid
    and on at least two sides, every free cell reached from every door cell,
    no dead floor (a free cell more than the clearance's gap + 1 from every
    piece), the long side within the family's aspect cap, every piece
    reached on a use side, the open room's filler clear, reached and off
    every wall, no wall carrying more empty lines than the slack line
    (flush) or the filler's buffer line (open), stretch lines truly
    insertable, sleep counts and size band matching the pieces, symmetry
    where flagged, and ids, families, roles and groups known. ``groups`` is
    room_groups.load() data and ``lib`` a Library; either may be None to
    skip its checks."""
    errors = []
    seen = {}
    for room in rooms:
        file = room.get("_file", "rooms") if isinstance(room, dict) else "rooms"
        if isinstance(room, dict) and "_load_error" in room:
            errors.append(f"{file}: cannot be read ({room['_load_error']})")
            continue
        rid = room.get("id") if isinstance(room, dict) else None
        inner = []
        _check_room(room, groups, lib, inner.append, True)
        for msg in inner:
            errors.append(f"{file}: room {rid!r}: {msg}")
        if isinstance(rid, str):
            if rid in seen:
                errors.append(f"room id {rid!r} appears in "
                              f"{seen[rid]} and {file}")
            else:
                seen[rid] = file
    return errors


